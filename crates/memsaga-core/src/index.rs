//! `paths.json` (slug -> real path, per root) and `index.md` (a browsable table
//! of every mirrored project) at the repo root. Both are regenerated on every
//! sweep that commits; they are cheap and make the flat slug layout readable
//! on GitHub without any other tooling.

use crate::config::Config;
use crate::roots::{Entry, Scope};
use crate::slug;
use anyhow::Result;
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

pub fn write_index(cfg: &Config, scope: &Scope) -> Result<()> {
    let mut paths: BTreeMap<String, BTreeMap<String, String>> = BTreeMap::new();
    let mut md = String::new();
    writeln!(md, "# memsaga index\n")?;
    writeln!(md, "Generated by memsaga on every commit. Live files stay in each Claude Code config directory; this repo is a one-way mirror. Restore is an explicit `memsaga restore` action.\n")?;
    for root in &cfg.roots {
        let map = slug::map_from_history(root);
        let entries = scope.entries(root);
        writeln!(
            md,
            "## {} (`{}`)\n",
            root.label,
            slug::display_path(&root.path.to_string_lossy())
        )?;
        let files: Vec<_> = entries
            .iter()
            .filter(|e| matches!(e, Entry::File { .. }))
            .collect();
        let dirs: Vec<_> = entries
            .iter()
            .filter(|e| matches!(e, Entry::Dir { .. }))
            .collect();
        if !files.is_empty() || !dirs.is_empty() {
            let mut items = Vec::new();
            for e in files.iter().chain(dirs.iter()) {
                if let Entry::File { rel } | Entry::Dir { rel } = e {
                    items.push(format!("[{rel}]({}/{rel})", root.label));
                }
            }
            writeln!(md, "Config: {}\n", items.join(", "))?;
        }
        writeln!(md, "| Project | Files | Last modified | Slug |")?;
        writeln!(md, "|---|---|---|---|")?;
        let mut per_root: BTreeMap<String, String> = BTreeMap::new();
        let mut rows: Vec<(String, String, usize, String, String)> = Vec::new();
        for e in &entries {
            if let Entry::Memory { slug: s } = e {
                let dir = e.source(root);
                let (count, newest) = dir_stats(&dir);
                let real = slug::resolve(&map, s);
                if let Some(r) = &real {
                    per_root.insert(s.clone(), r.clone());
                }
                let label = real
                    .as_deref()
                    .map(slug::display_path)
                    .unwrap_or_else(|| format!("(unresolved) {s}"));
                let link = format!("{}/memory/{}", root.label, s);
                rows.push((label, link, count, newest, s.clone()));
            }
        }
        rows.sort();
        for (label, link, count, newest, s) in rows {
            writeln!(md, "| [{label}]({link}) | {count} | {newest} | `{s}` |")?;
        }
        writeln!(md)?;
        paths.insert(root.label.clone(), per_root);
    }
    let companions = list_companions(&cfg.repo.join("companion"));
    if !companions.is_empty() {
        writeln!(
            md,
            "## companion
"
        )?;
        writeln!(
            md,
            "Translations and annotations of documents that live in other repositories (see the `companion-docs` skill).
"
        )?;
        for c in &companions {
            writeln!(md, "- [{c}](companion/{})", link_dest(c))?;
        }
        writeln!(md)?;
    }
    std::fs::write(cfg.repo.join("index.md"), md)?;
    std::fs::write(
        cfg.repo.join("paths.json"),
        serde_json::to_string_pretty(&paths)? + "\n",
    )?;
    Ok(())
}

/// Percent-encode the characters that would break a Markdown link
/// destination; `/` and ordinary path characters stay readable.
fn link_dest(path: &str) -> String {
    let mut out = String::with_capacity(path.len());
    for b in path.bytes() {
        match b {
            b' ' | b'(' | b')' | b'[' | b']' | b'#' | b'%' | b'<' | b'>' | b'?' => {
                out.push_str(&format!("%{b:02X}"))
            }
            _ => out.push(b as char),
        }
    }
    out
}

/// Every file under `companion/`, relative, sorted.
fn list_companions(dir: &Path) -> Vec<String> {
    let mut out = Vec::new();
    if !dir.is_dir() {
        return out;
    }
    for item in walkdir::WalkDir::new(dir)
        .follow_links(false)
        .into_iter()
        .filter_map(|e| e.ok())
    {
        if item.file_type().is_file() {
            if let Ok(rel) = item.path().strip_prefix(dir) {
                out.push(rel.to_string_lossy().to_string());
            }
        }
    }
    out.sort();
    out
}

fn dir_stats(dir: &Path) -> (usize, String) {
    let mut count = 0;
    let mut newest: Option<std::time::SystemTime> = None;
    if let Ok(rd) = std::fs::read_dir(dir) {
        for e in rd.filter_map(|e| e.ok()) {
            if e.file_type().map(|t| t.is_file()).unwrap_or(false) {
                count += 1;
                if let Ok(m) = e.metadata() {
                    if let Ok(t) = m.modified() {
                        newest = Some(newest.map_or(t, |n| n.max(t)));
                    }
                }
            }
        }
    }
    let when = newest
        .map(|t| {
            chrono::DateTime::<chrono::Local>::from(t)
                .format("%Y-%m-%d")
                .to_string()
        })
        .unwrap_or_default();
    (count, when)
}
