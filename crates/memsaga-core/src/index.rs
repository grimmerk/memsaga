//! `paths.json` (repository memory name -> real path with `~` for home, per
//! root) and `index.md` (a browsable table
//! of every mirrored project) at the repo root. Both are regenerated on every
//! sweep that commits; they are cheap and make the flat slug layout readable
//! on GitHub without any other tooling.

use crate::config::Config;
use crate::git::Git;
use crate::slug;
use crate::state::State;
use anyhow::Result;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

/// Memory folders a merge changed (`<label>/memory/<name>`). After a merge
/// that kept this machine's `index.md` (a conflict in generated files), their
/// rows may still hold this side's older date, so the next index asks git for
/// those dates instead of carrying them over.
const RECHECK: &str = "index-recheck.json";

/// Remember the memory folders among `changed` (paths a merge changed).
pub fn note_merged(state: &State, changed: &[String]) -> Result<()> {
    let mut dirs = load_recheck(state);
    let before = dirs.len();
    dirs.extend(changed.iter().filter_map(|p| memory_dir_of(p)));
    if dirs.len() == before {
        return Ok(());
    }
    state.write_marker(RECHECK, &serde_json::to_string(&dirs)?)
}

/// Forget them once a sweep has written an index with their dates.
pub fn clear_merged(state: &State) {
    state.remove(RECHECK);
}

fn load_recheck(state: &State) -> BTreeSet<String> {
    std::fs::read_to_string(state.marker(RECHECK))
        .ok()
        .and_then(|t| serde_json::from_str(&t).ok())
        .unwrap_or_default()
}

/// `<label>/memory/<name>` for a path inside a memory folder.
fn memory_dir_of(path: &str) -> Option<String> {
    let parts: Vec<&str> = path.split('/').collect();
    (parts.len() >= 3 && parts[1] == crate::roots::MEMORY_DIR).then(|| parts[..3].join("/"))
}

pub fn write_index(cfg: &Config) -> Result<()> {
    let mut paths: BTreeMap<String, BTreeMap<String, String>> = BTreeMap::new();
    // The slug -> path map is derived from this machine's prompt history; a
    // machine with less history (a new one) must not erase what another
    // machine already resolved, so the previous map is the fallback.
    let previous: BTreeMap<String, BTreeMap<String, String>> =
        std::fs::read_to_string(cfg.repo.join("paths.json"))
            .ok()
            .and_then(|t| serde_json::from_str(&t).ok())
            .unwrap_or_default();
    let previous_sections =
        sections_by_root(&std::fs::read_to_string(cfg.repo.join("index.md")).unwrap_or_default());
    // Everything below comes from the repository, not from this machine's
    // live files, so every machine writes the same index for the same
    // repository state (grimmerk/memsaga#24).
    let changed = changed_memory_dirs(cfg);
    let recheck = load_recheck(&State::new(cfg.state_dir()));
    let today = chrono::Local::now().format("%Y-%m-%d").to_string();
    let mut md = String::new();
    writeln!(md, "# memsaga index\n")?;
    writeln!(md, "Generated by memsaga on every commit. Live files stay in each Claude Code config directory; this repo mirrors them. An edit made here (or on GitHub) is kept and reaches the live file through `memsaga sync`, `memsaga pull` or the session hooks; `memsaga restore` brings back an older version.\n")?;
    for root in &cfg.roots {
        let base = cfg.repo.join(&root.label);
        if !base.is_dir() {
            if let Some(sec) = previous_sections.get(&root.label) {
                md.push_str(sec);
            }
            if let Some(prev) = previous.get(&root.label) {
                paths.insert(root.label.clone(), prev.clone());
            }
            continue;
        }
        let map = if root.path.is_dir() {
            slug::map_from_history(root)
        } else {
            Default::default()
        };
        writeln!(
            md,
            "## {} (`{}`)\n",
            root.label,
            slug::display_path(&root.path.to_string_lossy())
        )?;
        // What the repository holds for this root: files and links first,
        // then folders, each by name.
        let mut items: Vec<(bool, String)> = std::fs::read_dir(&base)
            .map(|rd| {
                rd.filter_map(|e| e.ok())
                    .map(|e| {
                        let is_dir = e.file_type().is_ok_and(|t| t.is_dir());
                        (is_dir, e.file_name().to_string_lossy().to_string())
                    })
                    .filter(|(_, n)| n != crate::roots::MEMORY_DIR && n != "projects")
                    .collect()
            })
            .unwrap_or_default();
        items.sort();
        if !items.is_empty() {
            let links: Vec<String> = items
                .iter()
                .map(|(_, n)| format!("[{n}]({}/{n})", root.label))
                .collect();
            writeln!(md, "Config: {}\n", links.join(", "))?;
        }
        let old_dates = previous_sections
            .get(&root.label)
            .map(|s| dates_by_name(s))
            .unwrap_or_default();
        writeln!(md, "| Project | Files | Last modified | Slug |")?;
        writeln!(md, "|---|---|---|---|")?;
        let mut per_root: BTreeMap<String, String> = BTreeMap::new();
        let mut rows: Vec<(String, String, usize, String, String)> = Vec::new();
        let memory = base.join(crate::roots::MEMORY_DIR);
        let mut names: Vec<String> = std::fs::read_dir(&memory)
            .map(|rd| {
                rd.filter_map(|e| e.ok())
                    .filter(|e| e.file_type().is_ok_and(|t| t.is_dir()))
                    .map(|e| e.file_name().to_string_lossy().to_string())
                    .collect()
            })
            .unwrap_or_default();
        names.sort();
        for name in names {
            let dir = memory.join(&name);
            let count = std::fs::read_dir(&dir)
                .map(|rd| {
                    rd.filter_map(|e| e.ok())
                        .filter(|e| e.file_type().is_ok_and(|t| t.is_file()))
                        .count()
                })
                .unwrap_or(0);
            // Changed in this commit: today. Otherwise the date the index
            // already had, so no git call; only a project the index lacks
            // asks git for its last commit.
            let rel = format!("{}/{}/{name}", root.label, crate::roots::MEMORY_DIR);
            let newest = if changed.contains(&rel) {
                today.clone()
            } else if recheck.contains(&rel) {
                last_commit_date(cfg, &rel)
            } else if let Some(d) = old_dates.get(&name) {
                d.clone()
            } else {
                last_commit_date(cfg, &rel)
            };
            let s = crate::roots::slug_of_repo_name(&name);
            // The previous map may be keyed by the repository name, or by
            // the live name it had before grimmerk/memsaga-private#25, whose values were
            // absolute: shorten those too.
            let prev = previous.get(&root.label);
            let real = slug::resolve(&map, &s).or_else(|| {
                prev.and_then(|m| m.get(&name).or_else(|| m.get(&s)))
                    .cloned()
            });
            let real = real.map(|p| slug::display_path(&p));
            if let Some(r) = &real {
                per_root.insert(name.clone(), r.clone());
            }
            let label = real
                .clone()
                .unwrap_or_else(|| format!("(unresolved) {name}"));
            let link = format!("{}/memory/{}", root.label, name);
            rows.push((label, link, count, newest, name));
        }
        rows.sort();
        for (label, link, count, newest, s) in rows {
            writeln!(md, "| [{label}]({link}) | {count} | {newest} | `{s}` |")?;
        }
        writeln!(md)?;
        paths.insert(root.label.clone(), per_root);
    }
    let companions: Vec<String> = crate::companion::list(&cfg.repo, None)
        .into_iter()
        .map(|c| c.rel)
        .collect();
    if !companions.is_empty() {
        writeln!(
            md,
            "## companion
"
        )?;
        writeln!(
            md,
            "Translations and annotations of documents that live in other repositories (see the `companion-docs` skill).
"
        )?;
        for c in &companions {
            writeln!(md, "- [{c}](companion/{})", link_dest(c))?;
        }
        writeln!(md)?;
    }
    std::fs::write(cfg.repo.join("index.md"), md)?;
    std::fs::write(
        cfg.repo.join("paths.json"),
        serde_json::to_string_pretty(&paths)? + "\n",
    )?;
    Ok(())
}

/// Percent-encode the characters that would break a Markdown link
/// destination; `/` and ordinary path characters stay readable.
fn link_dest(path: &str) -> String {
    let mut out = String::with_capacity(path.len());
    for b in path.bytes() {
        match b {
            b' ' | b'(' | b')' | b'[' | b']' | b'#' | b'%' | b'<' | b'>' | b'?' => {
                out.push_str(&format!("%{b:02X}"))
            }
            _ => out.push(b as char),
        }
    }
    out
}

/// The `## <label> (...)` sections of a previous index.md, keyed by label,
/// each including its trailing blank line.
fn sections_by_root(text: &str) -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    let mut current: Option<(String, String)> = None;
    for line in text.split_inclusive('\n') {
        if let Some(rest) = line.strip_prefix("## ") {
            if let Some((label, body)) = current.take() {
                out.insert(label, body);
            }
            let label = rest.split_whitespace().next().unwrap_or("").to_string();
            current = Some((label, line.to_string()));
        } else if let Some((_, body)) = current.as_mut() {
            body.push_str(line);
        }
    }
    if let Some((label, body)) = current {
        out.insert(label, body);
    }
    out
}

/// `<label>/memory/<name>` folders with uncommitted changes in the clone:
/// what this sweep is about to commit.
fn changed_memory_dirs(cfg: &Config) -> BTreeSet<String> {
    let mut args = vec!["status", "--porcelain", "-z", "--untracked-files=all", "--"];
    let pathspecs: Vec<String> = cfg
        .roots
        .iter()
        .map(|r| format!("{}/{}", r.label, crate::roots::MEMORY_DIR))
        .collect();
    args.extend(pathspecs.iter().map(String::as_str));
    let out = Git::new(&cfg.repo).run_ok(&args).unwrap_or_default();
    // Each record is "XY path"; a rename or copy is followed by a record
    // holding only the old path.
    let mut paths = Vec::new();
    let mut records = out.split('\0').filter(|r| !r.is_empty());
    while let Some(r) = records.next() {
        let Some(path) = r.get(3..) else { continue };
        paths.push(path);
        if r.starts_with('R') || r.starts_with('C') {
            if let Some(old) = records.next() {
                paths.push(old);
            }
        }
    }
    paths.into_iter().filter_map(memory_dir_of).collect()
}

/// Date (`YYYY-MM-DD`) of the last commit that touched `rel`, or empty.
fn last_commit_date(cfg: &Config, rel: &str) -> String {
    Git::new(&cfg.repo)
        .run_ok(&["log", "-1", "--format=%cs", "--", rel])
        .map(|s| s.trim().to_string())
        .unwrap_or_default()
}

/// Project name -> "Last modified" in one section of a previous index.
fn dates_by_name(section: &str) -> BTreeMap<String, String> {
    section
        .lines()
        .filter_map(|l| {
            let cells: Vec<&str> = l.trim().trim_matches('|').split(" | ").collect();
            if cells.len() != 4 {
                return None;
            }
            let name = cells[3].trim().trim_matches('`');
            let date = cells[2].trim();
            (date.len() == 10 && date.as_bytes()[4] == b'-')
                .then(|| (name.to_string(), date.to_string()))
        })
        .collect()
}
